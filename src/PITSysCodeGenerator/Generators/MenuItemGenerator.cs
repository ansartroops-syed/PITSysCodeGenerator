using PITSysCodeGenerator.Helpers;
using PITSysCodeGenerator.Models;
using System.Text;

namespace PITSysCodeGenerator.Generators
{
    /// <summary>
    /// Generates the Action MenuItem XML definition for D365FO.
    /// </summary>
    public class MenuItemGenerator : ICodeGenerator
    {
        public string Generate(GeneratorOptions options)
        {
            var sb = new StringBuilder();
            var menuItemName = options.MenuItemName;
            var controllerName = options.ControllerClassName;
            var caption = options.BatchJobCaption ?? options.BaseClassName;

            sb.AppendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
            sb.AppendLine($"<!-- Generated by PITSysCodeGenerator on {System.DateTime.Now:yyyy-MM-dd HH:mm:ss} -->");
            sb.AppendLine("<AxMenuItemAction xmlns:i=\"http://www.w3.org/2001/XMLSchema-instance\">");
            sb.AppendLine($"{CodeFormatter.Indent}<Name>{menuItemName}</Name>");
            sb.AppendLine($"{CodeFormatter.Indent}<Label>{caption}</Label>");
            sb.AppendLine($"{CodeFormatter.Indent}<ObjectType>Class</ObjectType>");
            sb.AppendLine($"{CodeFormatter.Indent}<Object>{controllerName}</Object>");
            sb.AppendLine($"{CodeFormatter.Indent}<RunOn>Server</RunOn>");
            sb.AppendLine($"{CodeFormatter.Indent}<NeedsRecord>No</NeedsRecord>");
            sb.AppendLine($"{CodeFormatter.Indent}<OpenMode>Auto</OpenMode>");
            sb.AppendLine("</AxMenuItemAction>");

            sb.AppendLine();
            sb.AppendLine("<!--");
            sb.AppendLine("  To add this menu item to D365FO:");
            sb.AppendLine($"  1. In your D365FO project, add a new Action Menu Item named '{menuItemName}'");
            sb.AppendLine($"  2. Set Object Type = Class");
            sb.AppendLine($"  3. Set Object = {controllerName}");
            sb.AppendLine($"  4. Set Label = \"{caption}\"");
            sb.AppendLine("  5. Add it to the appropriate menu or workspace");
            sb.AppendLine("-->");

            return sb.ToString();
        }

        public string GetFileName(GeneratorOptions options) => $"{options.MenuItemName}_MenuItem";
    }
}