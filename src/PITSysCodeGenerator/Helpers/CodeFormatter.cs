using System;
using System.Text;

namespace PITSysCodeGenerator.Helpers
{
    /// <summary>
    /// Helper for formatting X++ code with proper indentation and line spacing.
    /// </summary>
    public static class CodeFormatter
    {
        /// <summary>
        /// Standard indentation (4 spaces, X++ convention).
        /// </summary>
        public const string Indent = "    ";

        /// <summary>
        /// Double indentation.
        /// </summary>
        public const string Indent2 = "        ";

        /// <summary>
        /// Triple indentation.
        /// </summary>
        public const string Indent3 = "            ";

        /// <summary>
        /// Creates an X++ file header comment block.
        /// </summary>
        public static string GenerateFileHeader(string className, string description)
        {
            var sb = new StringBuilder();
            sb.AppendLine("/// <summary>");
            sb.AppendLine($"/// {description}");
            sb.AppendLine("/// </summary>");
            sb.AppendLine($"/// <remarks>");
            sb.AppendLine($"/// Generated by PITSysCodeGenerator on {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine($"/// </remarks>");
            return sb.ToString();
        }

        /// <summary>
        /// Creates an X++ method summary comment.
        /// </summary>
        public static string GenerateMethodComment(string summary, string returns = null, params (string name, string desc)[] parameters)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"{Indent}/// <summary>");
            sb.AppendLine($"{Indent}/// {summary}");
            sb.AppendLine($"{Indent}/// </summary>");

            foreach (var param in parameters)
            {
                sb.AppendLine($"{Indent}/// <param name=\"_{param.name}\">{param.desc}</param>");
            }

            if (!string.IsNullOrEmpty(returns))
            {
                sb.AppendLine($"{Indent}/// <returns>{returns}</returns>");
            }

            return sb.ToString();
        }

        /// <summary>
        /// Wraps content in an X++ class declaration.
        /// </summary>
        public static string WrapInClass(string classAttributes, string className, string extends, string body)
        {
            var sb = new StringBuilder();

            if (!string.IsNullOrEmpty(classAttributes))
            {
                sb.AppendLine(classAttributes);
            }

            if (!string.IsNullOrEmpty(extends))
            {
                sb.AppendLine($"class {className} extends {extends}");
            }
            else
            {
                sb.AppendLine($"class {className}");
            }

            sb.AppendLine("{");
            sb.Append(body);
            sb.AppendLine("}");

            return sb.ToString();
        }
    }
}